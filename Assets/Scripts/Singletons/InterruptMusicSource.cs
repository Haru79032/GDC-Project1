using UnityEngine;

public class InterruptMusicSource : MonoBehaviour
{
    public static InterruptMusicSource Instance {get; private set;}
    private void Awake()
    {
        if (Instance == null)
        {
            Instance = this;
            DontDestroyOnLoad(gameObject);
        }
        else
        {
            Destroy(gameObject);
        }
    }
}